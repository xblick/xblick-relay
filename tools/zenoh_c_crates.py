"""The Rust crates that zenoh-c's libzenohc.so is built from, with the licence texts each crate ships: the file
licenses/zenoh-c-crates.txt of the wheel xblick-relay. tools/build_wheel.sh compares it with its build.

    python tools/zenoh_c_crates.py <zenoh-c source dir> > licenses/zenoh-c-crates.txt

Run it after a build of zenoh-c (the crates are then in cargo's cache; it works offline and with the Cargo.lock of
zenoh-c). The crates: cargo tree's normal dependencies of zenoh-c with the features of its release (shared-memory,
unstable) for x86_64-unknown-linux-gnu. That includes proc-macro crates, which run in the compiler and are not part of
the library; build dependencies are left out. The licence expression is the one of each crate's Cargo.toml; the texts
are the files named LICENSE*, LICENCE*, COPYING* or NOTICE* at the top of each crate's package, each distinct text once.
"""

import hashlib
import json
import subprocess
import sys
from pathlib import Path

TARGET = "x86_64-unknown-linux-gnu"
FEATURES = "shared-memory,unstable"
PREFIXES = ("LICENSE", "LICENCE", "COPYING", "NOTICE")


def cargo(src: Path, *args: str) -> str:
    return subprocess.run(["cargo", *args], cwd=src, check=True, capture_output=True, text=True).stdout


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit("usage: zenoh_c_crates.py <zenoh-c source dir>")
    src = Path(sys.argv[1])
    tree = cargo(src, "tree", "--locked", "--offline", "-e", "normal", "--target", TARGET, "--features", FEATURES,
                 "--prefix", "none", "--format", "{p}")
    linked = set()
    for line in tree.splitlines():
        parts = line.replace(" (*)", "").split()
        if parts:
            linked.add((parts[0], parts[1].lstrip("v")))
    meta = json.loads(cargo(src, "metadata", "--locked", "--offline", "--format-version", "1",
                            "--filter-platform", TARGET, "--features", FEATURES))
    packages = {(p["name"], p["version"]): p for p in meta["packages"]}
    missing = linked - packages.keys()
    if missing:
        sys.exit(f"cargo metadata lacks {sorted(missing)}")

    texts: dict[str, tuple[int, str, list[str]]] = {}  # digest -> (number, text, crate files)
    rows = []
    for key in sorted(linked):
        package = packages[key]
        name, version = key
        root = Path(package["manifest_path"]).parent
        files = sorted(f for f in root.iterdir() if f.is_file() and f.name.upper().startswith(PREFIXES))
        numbers = []
        for f in files:
            text = f.read_text(encoding="utf-8", errors="replace")
            digest = hashlib.sha256(text.encode()).hexdigest()
            if digest not in texts:
                texts[digest] = (len(texts) + 1, text, [])
            texts[digest][2].append(f"{name} {version} {f.name}")
            numbers.append(f"[T{texts[digest][0]}]")
        if package.get("license_file") and not files:
            numbers.append(f"license-file {package['license_file']} (not found at the package's top)")
        licence = package.get("license") or "(no licence expression in Cargo.toml)"
        rows.append(f"{name} {version}  {licence}  {' '.join(numbers) or '(ships no licence file)'}")

    zenoh_c = next(p for p in meta["packages"] if p["name"] == "zenoh-c")
    header = [
        "Rust crates in libzenohc.so of the wheel xblick-relay",
        f"zenoh-c {zenoh_c['version']}, features {FEATURES}, target {TARGET}; generated by "
        "tools/zenoh_c_crates.py from zenoh-c's Cargo.lock.",
        "Per crate: name, version, the licence expression of its Cargo.toml, and the licence files it ships ([T<n>],",
        "texts below).",
        "",
    ]
    out = header + rows + [""]
    for number, text, owners in sorted(texts.values()):
        out.append(f"==== [T{number}] shipped by {len(owners)} crate(s)")
        out.append(text.rstrip("\n"))
        out.append("")
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
